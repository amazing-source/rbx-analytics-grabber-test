// Generates the MEASUREMENT half of each 2026-09-11 game doc.
// Every number comes from tools/lib.js `daily()`/`byBreakdown()` so the
// headline-series rule, FILLED_ZERO and partial handling are the repo's single
// implementation. Prose/interpretation is added by hand on top.
const fs=require("fs");
const { daily, byBreakdown } = require("./lib.js");
const OUT="C:/Users/bfhdh/Desktop/rbx-analytics-grabber-test/reports/2026-09-11/";

const GAMES=[
 ["9963622286","Brainrot","brainrot","Become a Brainrot"],
 ["10030829154","Waterslide","waterslide","Climb Waterslide and Slide"],
 ["10399712766","Monkey","monkey","+1 Banana Monkey Destruction"],
 ["10565445771","Verity","verity","Verity Companion [AI]"],
 ["10638354731","Seal","seal","Seal A Driveway"],
 ["9610561918","KnifeFarm","knife-farm","My Knife Farm"],
];
// weekday-matched: both spans are Sat,Sun,Mon,Tue,Wed
const PRE=["2026-08-29","2026-08-30","2026-08-31","2026-09-01","2026-09-02"];
const POST=["2026-09-05","2026-09-06","2026-09-07","2026-09-08","2026-09-09"];
const mean=(m,ds)=>{const v=ds.map(d=>m&&m.get(d)).filter(x=>x!=null&&Number.isFinite(x));return v.length?v.reduce((a,b)=>a+b,0)/v.length:null;};
const rel=(a,b)=>(a==null||b==null||!b)?"—":(((a/b)-1)*100).toFixed(1)+"%";
const fmt=(v,dp)=>v==null?"—":(dp?Number(v).toFixed(dp):Math.round(v).toLocaleString("en-US"));

const ROWS=[
 ["Peak concurrents","PeakConcurrentPlayers",0,"volume"],
 ["DAU","DailyActiveUsers",0,"volume"],
 ["Impressions (unique users)","UniqueUsersWithImpressions",0,"volume"],
 ["Impression→play CVR","EndToEndCVR",4,"rate"],
 ["D1 retention","ForwardD1Retention",4,"rate"],
 ["Session length (min)","AverageSessionLengthMinutes",2,"rate"],
 ["Play min per DAU","AveragePlayTimeMinutesPerDAU",2,"rate"],
 ["Revenue (R$)","DailyRevenue",0,"volume"],
 ["ARPU (R$)","AverageRevenuePerUser",4,"rate"],
 ["Paying-user CVR","PayingUsersCVR",4,"rate"],
 ["RFY play-through rate","RFYPlayThroughRate",4,"rate"],
 ["RFY bounce <60s","RFYDuration0To60",4,"rate"],
 ["RFY D1 playtime","RFYD1Playtime",3,"rate"],
 ["RFY D2–7 play days","RFYD2To7PlayDays",3,"rate"],
 ["RFY D1 qualified sessions","RFYD1QualifiedPlaySessions",3,"rate"],
];
const dow=d=>["Sun","Mon","Tue","Wed","Thu","Fri","Sat"][new Date(d+"T00:00:00Z").getUTCDay()];

for(const [id,short,slug,full] of GAMES){
  let md=`<!-- generated by tools/mk-0911.js — measurements only, do not hand-edit the tables -->\n\n`;
  md+=`## Measurements\n\n`;
  md+=`**Matched-weekday comparison.** Both spans are Sat·Sun·Mon·Tue·Wed, five days each, so\n`;
  md+=`the weekly shape divides out rather than being averaged away.\n\n`;
  md+=`- **Before:** 2026-08-29 → 2026-09-02 (pre-publish)\n- **After:** 2026-09-05 → 2026-09-09 (post-publish, excludes the publish days themselves)\n\n`;
  md+=`| Metric | Kind | Before | After | Δ |\n|---|---|---|---|---|\n`;
  for(const [lbl,met,dp,kind] of ROWS){
    let m=null; try{m=daily(id,met);}catch(e){}
    const a=mean(m,PRE), b=mean(m,POST);
    md+=`| ${lbl} | ${kind} | ${fmt(a,dp)} | ${fmt(b,dp)} | ${rel(b,a)} |\n`;
  }
  md+=`\nVolume deltas are *not* like-for-like across a shrinking audience — read the rate rows for that.\n`;

  // daily series
  md+=`\n### Daily series (settled days only)\n\n`;
  md+=`| Date | Day | PCU | DAU | Impressions | D1 | Session | Revenue R$ | ARPU |\n|---|---|---|---|---|---|---|---|---|\n`;
  const dm={}; for(const k of ["PeakConcurrentPlayers","DailyActiveUsers","UniqueUsersWithImpressions","ForwardD1Retention","AverageSessionLengthMinutes","DailyRevenue","AverageRevenuePerUser"]){ try{dm[k]=daily(id,k);}catch(e){dm[k]=null;} }
  const days=[]; {const d=new Date("2026-08-29T00:00:00Z"); while(d<=new Date("2026-09-10T00:00:00Z")){days.push(d.toISOString().slice(0,10));d.setUTCDate(d.getUTCDate()+1);} }
  for(const d of days){
    const g=(k,dp)=>{const m=dm[k];return (m&&m.has(d))?fmt(m.get(d),dp):"—";};
    md+=`| ${d} | ${dow(d)} | ${g("PeakConcurrentPlayers",0)} | ${g("DailyActiveUsers",0)} | ${g("UniqueUsersWithImpressions",0)} | ${g("ForwardD1Retention",4)} | ${g("AverageSessionLengthMinutes",2)} | ${g("DailyRevenue",0)} | ${g("AverageRevenuePerUser",4)} |\n`;
  }

  // funnel
  let bd=null; try{bd=byBreakdown(id,"FunnelCohortCompletionRate","FunnelStep");}catch(e){}
  if(bd&&bd.size){
    md+=`\n### Funnel — cohort completion by step\n\n`;
    md+=`Before = 2026-08-29→09-02, After = 2026-09-05→09-08. The newest funnel day is\n`;
    md+=`excluded: it moves by up to 5.5pp on its own as the cohort settles.\n\n`;
    md+=`| Step | Before | After | Δpp |\n|---|---|---|---|\n`;
    const FPOST=["2026-09-05","2026-09-06","2026-09-07","2026-09-08"];
    const rows=[];
    for(const [step,m] of bd){ const a=mean(m,PRE), b=mean(m,FPOST); if(a==null||b==null)continue; rows.push([step,a,b,(b-a)*100]); }
    rows.sort((x,y)=>x[3]-y[3]);
    for(const [s,a,b,d] of rows) md+=`| ${s} | ${(a*100).toFixed(1)}% | ${(b*100).toFixed(1)}% | ${d>0?"+":""}${d.toFixed(1)} |\n`;
  }

  // acquisition split
  md+=`\n### D1 retention by acquisition source\n\n`;
  md+=`\`Friends\` arrives by social invite and never sees a thumbnail; \`Search\` went looking\n`;
  md+=`for the game by name. If those move with the rest, creative and traffic-mix are ruled out.\n\n`;
  let ab=null; try{ab=byBreakdown(id,"ForwardD1Retention","AcquisitionSource");}catch(e){}
  if(ab&&ab.size){
    md+=`| Source | Before | After | Δ |\n|---|---|---|---|\n`;
    for(const [k,m] of ab){ const a=mean(m,PRE),b=mean(m,POST); if(a==null||b==null)continue;
      md+=`| ${k} | ${(a*100).toFixed(2)}% | ${(b*100).toFixed(2)}% | ${rel(b,a)} |\n`; }
  } else md+=`_not in corpus_\n`;

  fs.writeFileSync(OUT+slug+"-measurements.md",md);
  console.log("wrote "+slug+"-measurements.md");
}
